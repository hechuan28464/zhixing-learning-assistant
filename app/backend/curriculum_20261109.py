def ordered_question(lid,purpose,question):
    result=deepcopy(question);indices=list(range(len(result['options'])))
    family='guided-practice' if purpose in ('practice','remediation') else purpose
    random.Random(hashlib.sha256((lid+':'+family+':option-order-v1').encode()).digest()).shuffle(indices)
    original=ord(result['answer'])-65;result['options']=[result['options'][i] for i in indices]
    result['answer']=chr(65+indices.index(original))
    return result

